package geometry

import "github.com/elebirds/panoptes/internal/domain"

func Manhattan(a, b domain.Position) int {
	dx := a.X - b.X
	if dx < 0 {
		dx = -dx
	}
	dy := a.Y - b.Y
	if dy < 0 {
		dy = -dy
	}
	return dx + dy
}
